"""
UmiSlim Feetech Module

A parallel gripper driven by a single Feetech servo. It is commanded by the
desired **finger aperture in centimetres**; the module translates that aperture
into the servo's normalized command space, which each backend then maps to the
physical target:

* **Real hardware** — normalized command -> servo counts via the Feetech
  calibration (recorded closed/open positions).
* **Simulation** — normalized command -> the ``left_manifold_to_rail`` prismatic
  joint via the ``sim:`` block in ``conf_umi_slim_feetech.yaml``. The exported
  MuJoCo model only actuates that one joint; an ``<equality>`` constraint
  (ratio -1, generated by onshape-to-robot from the CAD relation) drives the
  opposite finger, so a single command opens/closes both jaws symmetrically.

Because the module always emits the *same* normalized value to
``write_actuators``, real and sim stay consistent as long as their endpoints
(calibration open/closed vs. the ``sim:`` range) describe the same physical
apertures configured here as ``aperture_open_cm`` / ``aperture_closed_cm``.

Trajectory upsampling uses the core GripperModule scalar path
(``interpolator_type: scalar`` in yaml): sparse ``SCHEDULE_WAYPOINT``
apertures are in **centimetres**, interpolated at the module rate, then
converted to normalized servo ``[-100, 100]`` on write, bounded by
``aperture_closed_cm`` / ``aperture_open_cm``.
"""

from logging import getLogger

from solarian.core.gripper_module import GripperModule
from solarian.core.configs import ModuleConfig
from solarian.core.data import PosData
from solarian_feetech.actuator import FeetechServo
from solarian_umi_slim.aperture import (
    APERTURE_CLOSED_CM,
    APERTURE_OPEN_CM,
    aperture_to_norm as cm_to_norm,
    norm_to_aperture as norm_to_cm,
    resolve_aperture_limits,
)

logger = getLogger("module")


class UmiSlimFeetechConfig(ModuleConfig):
    """Config for the Feetech-actuated UMI-slim gripper.

    ``aperture_closed_cm`` / ``aperture_open_cm`` are the physical finger
    aperture (fingertip separation) at the two ends of travel. They must
    match the servo calibration and the ``sim:`` joint range. Defaults are
    ruler measurements (fully closed 0 cm, fully open 8.5 cm). The old CAD
    pair 2.94 / 13.84 is rejected at conversion time.
    """

    calibration_file: str | None = None
    aperture_closed_cm: float = APERTURE_CLOSED_CM
    aperture_open_cm: float = APERTURE_OPEN_CM


class UmiSlimFeetechModule(GripperModule):
    config_class = UmiSlimFeetechConfig

    # Single logical actuator, matching the single physical Feetech servo.
    # Declared so the core scalar interpolator knows which field to drive.
    scalar_actuator = "gripper"
    gripper = FeetechServo()

    def _aperture_limits(self) -> tuple[float, float]:
        return resolve_aperture_limits(
            getattr(self.cfg, "aperture_closed_cm", None),
            getattr(self.cfg, "aperture_open_cm", None),
        )

    @property
    def open_value(self) -> float:
        """Open end of travel: fully open finger aperture in cm."""
        return self._aperture_limits()[1]

    def initialize(self):
        super().initialize()
        lo, hi = self._aperture_limits()
        open_norm = self.aperture_to_norm(hi)
        if abs(open_norm - 100.0) > 0.5:
            logger.error(
                "UmiSlim Feetech '%s': %.2f cm should map to servo 100, got %.1f "
                "(limits %.2f–%.2f). Restart run-robot so this process loads "
                "the current plugin.",
                self.name,
                hi,
                open_norm,
                lo,
                hi,
            )
        logger.info(
            "UmiSlim Feetech '%s': aperture %.2f–%.2f cm ↔ servo -100–100 "
            "(%.2f cm → %.1f)",
            self.name,
            lo,
            hi,
            hi,
            open_norm,
        )

        # Gentle position-control gains for the gripper servo. These are no-ops
        # in simulation (the MuJoCo world ignores hardware config writes).
        self.disable_torque()
        self.configure_components({
            "Return_Delay_Time": 0,
            "Maximum_Acceleration": 254,
            "Acceleration": 254,
            "Operating_Mode": 0,
            "P_Coefficient": 32,
            "I_Coefficient": 2,
            "D_Coefficient": 2,
        })
        # Hold present before torque-on so a stale Goal_Position cannot slam
        # the jaws into a hard stop on startup.
        self._hold_present_pose()
        self.enable_torque()

    # ---- safety hooks (called by the align-ik CLI) -------------------------
    def _hold_present_pose(self) -> None:
        """Set the gripper goal to its present position (no jump on torque-on)."""
        present = self.read_sensors(PosData, ["gripper"])
        self.module_bus.write(
            {"gripper": PosData(value=present["gripper"]["value"])}, normalize=True
        )

    def enter_safe_hold(self) -> None:
        """Hold the gripper where it is until armed (no jump on power-up)."""
        self._hold_present_pose()
        self.enable_torque()

    def on_arm(self) -> None:
        """Re-hold + re-enable torque so arming never jumps the gripper."""
        self._hold_present_pose()
        self.enable_torque()

    def on_disarm(self) -> None:
        pass

    # ---- aperture <-> normalized command -----------------------------------
    def aperture_to_norm(self, aperture_cm: float) -> float:
        """Map a finger aperture (cm) to the servo's normalized command [-100, 100].

        -100 -> fully closed, 100 -> fully open. Legacy CAD limits (2.94 / 13.84)
        are ignored so an 8.5 cm command cannot collapse to servo ~2.
        """
        lo, hi = self._aperture_limits()
        return cm_to_norm(aperture_cm, lo, hi)

    def norm_to_aperture(self, norm: float) -> float:
        """Inverse of :meth:`aperture_to_norm` (normalized [-100, 100] -> cm)."""
        lo, hi = self._aperture_limits()
        return norm_to_cm(norm, lo, hi)

    def read_aperture_cm(self) -> float:
        """Current finger aperture in cm, read back from the servo/sim joint."""
        pos = self.read_sensors(PosData, ["gripper"])
        return self.norm_to_aperture(pos["gripper"]["value"])

    # Scalar interpolator works in aperture (cm); convert at the write/seed edge.
    def _scalar_to_actuator(self, value: float) -> float:
        return self.aperture_to_norm(value)

    def _actuator_to_scalar(self, value: float) -> float:
        return self.norm_to_aperture(value)


# Historical names used before the Feetech/Robstride split.
UmiSlimConfig = UmiSlimFeetechConfig
UmiSlimModule = UmiSlimFeetechModule
