"""
UmiSlim Module

A parallel gripper driven by a single Feetech servo. It is commanded by the
desired **finger aperture in centimetres**; the module translates that aperture
into the servo's normalized command space, which each backend then maps to the
physical target:

* **Real hardware** — normalized command -> servo counts via the Feetech
  calibration (recorded closed/open positions).
* **Simulation** — normalized command -> the ``left_manifold_to_rail`` prismatic
  joint via the ``sim:`` block in ``conf.yaml``. The exported MuJoCo model only
  actuates that one joint; an ``<equality>`` constraint (ratio -1, generated by
  onshape-to-robot from the CAD relation) drives the opposite finger, so a
  single command opens/closes both jaws symmetrically.

Because the module always emits the *same* normalized value to
``write_actuators``, real and sim stay consistent as long as their endpoints
(calibration open/closed vs. the ``sim:`` range) describe the same physical
apertures configured here as ``aperture_open_cm`` / ``aperture_closed_cm``.
"""

from solarian.core.module import Module
from solarian.core.configs import ModuleConfig
from solarian.core.data import PosData
from solarian.core.action import ActionType, ModuleAction, action_handler
from solarian_feetech.actuator import FeetechServo


class UmiSlimConfig(ModuleConfig):
    """Config for the UMI-slim gripper.

    ``aperture_closed_cm`` / ``aperture_open_cm`` define the physical finger
    aperture (fingertip separation) at the two ends of travel. They are the
    single source of truth for the ``cm <-> normalized`` conversion and must
    correspond to the same physical extremes as the servo calibration and the
    ``sim:`` joint range. Defaults are the fingertip separations measured on the
    exported model (joint 0.0 m = open, 0.0545 m = closed).
    """

    calibration_file: str | None = None
    aperture_closed_cm: float = 2.94
    aperture_open_cm: float = 13.84


class UmiSlimModule(Module):
    config_class = UmiSlimConfig

    # Single logical actuator, matching the single physical Feetech servo.
    gripper = FeetechServo()

    def initialize(self):
        super().initialize()

        self.target = None

        # Gentle position-control gains for the gripper servo. These are no-ops
        # in simulation (the MuJoCo world ignores hardware config writes).
        self.disable_torque()
        self.configure_components({
            "Return_Delay_Time": 0,
            "Maximum_Acceleration": 254,
            "Acceleration": 254,
            "Operating_Mode": 0,
            "P_Coefficient": 32,
            "I_Coefficient": 2,
            "D_Coefficient": 2,
        })
        # Hold present before torque-on so a stale Goal_Position cannot slam
        # the jaws into a hard stop on startup.
        self._hold_present_pose()
        self.enable_torque()

    # ---- safety hooks (see Robot.safety_arming) ----------------------------
    def _hold_present_pose(self) -> None:
        """Set the gripper goal to its present position (no jump on torque-on).

        Bypasses ``write_actuators`` (gated while disarmed) by writing the bus
        directly.
        """
        present = self.read_sensors(PosData, ["gripper"])
        self.module_bus.write(
            {"gripper": PosData(value=present["gripper"]["value"])}, normalize=True
        )

    def enter_safe_hold(self) -> None:
        """Hold the gripper where it is until armed (no jump on power-up)."""
        self._hold_present_pose()
        self.enable_torque()

    def on_arm(self) -> None:
        """Re-hold + re-enable torque so arming never jumps the gripper."""
        self._hold_present_pose()
        self.enable_torque()

    def on_disarm(self) -> None:
        pass

    # ---- aperture <-> normalized command -----------------------------------
    def aperture_to_norm(self, aperture_cm: float) -> float:
        """Map a finger aperture (cm) to the servo's normalized command [-100, 100].

        -100 -> fully closed (``aperture_closed_cm``), 100 -> fully open
        (``aperture_open_cm``). Clamped to the valid range.
        """
        lo, hi = self.cfg.aperture_closed_cm, self.cfg.aperture_open_cm
        if hi == lo:
            return -100.0
        norm = (aperture_cm - lo) / (hi - lo) * 200.0 - 100.0
        return max(-100.0, min(100.0, norm))

    def norm_to_aperture(self, norm: float) -> float:
        """Inverse of :meth:`aperture_to_norm` (normalized [-100, 100] -> cm)."""
        lo, hi = self.cfg.aperture_closed_cm, self.cfg.aperture_open_cm
        return lo + ((norm + 100.0) / 200.0) * (hi - lo)

    def read_aperture_cm(self) -> float:
        """Current finger aperture in cm, read back from the servo/sim joint."""
        pos = self.read_sensors(PosData, ["gripper"])
        return self.norm_to_aperture(pos["gripper"]["value"])

    # ---- control loop ------------------------------------------------------
    def control_step(self):
        if self.target is not None:
            self.write_actuators({"gripper": PosData(value=self.target)})
            self.target = None

    @action_handler(ActionType.SCHEDULE_WAYPOINT)
    def _handle_schedule_waypoint(self, action: ModuleAction, t_now: float) -> bool:
        """Accept a waypoint whose ``gripper`` value is an **aperture in cm**."""
        field = action.values().get("gripper")
        if field is not None:
            self.target = self.aperture_to_norm(field.value)
        return True
